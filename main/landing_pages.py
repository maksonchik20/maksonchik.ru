def landing_pricing(page: dict) -> list:
    if page.get("pricing_tiers"):
        return page["pricing_tiers"]
    preset = page.get("preset", "default")
    return LANDING_PRESETS[preset]["pricing"]


def landing_timelines(page: dict) -> list:
    if page.get("timelines"):
        return page["timelines"]
    preset = page.get("preset", "default")
    return LANDING_PRESETS[preset]["timelines"]


def landing_also_exclude(page: dict) -> frozenset[str]:
    if page.get("also_exclude"):
        return frozenset(page["also_exclude"])
    preset = page.get("preset", "default")
    return ALSO_EXCLUDE_BY_PRESET.get(preset, frozenset())


def landing_also_exclude_urls(page: dict) -> frozenset[str]:
    preset = page.get("preset", "default")
    return ALSO_EXCLUDE_URLS_BY_PRESET.get(preset, frozenset())


def landing_also_extra(page: dict) -> list[dict]:
    preset = page.get("preset", "default")
    return ALSO_EXTRA_BY_PRESET.get(preset, [])

