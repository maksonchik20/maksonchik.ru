def _build_related_services(primary_slug: str) -> list[dict]:
    links = []
    for slug, label in STANDARD_SERVICE_LINKS:
        if slug == primary_slug:
            continue
        if slug not in SERVICE_LANDINGS:
            continue
        links.append({"url": f"/services/{slug}/", "label": label})
    links.append(
        {
            "url": "/blog/programma-loyalnosti-v-telegram/",
            "label": "Программу лояльности",
        }
    )
    return links


def _build_links_note(primary_slug: str, primary_label: str) -> str:
    parts = [f'<a href="/services/{primary_slug}/">{primary_label}</a>']
    for slug, label in STANDARD_SERVICE_LINKS:
        if slug == primary_slug:
            continue
        parts.append(f'<a href="/services/{slug}/">{label}</a>')
    parts.append('<a href="/blog/programma-loyalnosti-v-telegram/">программу лояльности</a>')
    if len(parts) == 1:
        return f"Подробнее: {parts[0]}."
    return "Также делаю: " + ", ".join(parts[:-1]) + " и " + parts[-1] + "."


def _article(
    slug: str,
    title: str,
    description: str,
    *,
    category: str,
    category_label: str,
    service_slug: str,
    service_label: str,
    sections: list[dict],
) -> dict:
    return {
        "slug": slug,
        "url": f"https://maksonchik.ru/blog/{slug}/",
        "title": title,
        "h1": title,
        "description": description,
        "category": category,
        "category_label": category_label,
        "date_modified": CONTENT_LASTMOD,
        "date_modified_label": "18 августа 2026",
        "service_slug": service_slug,
        "service_url": f"/services/{service_slug}/",
        "service_label": service_label,
        "related_services": _build_related_services(service_slug),
        "links_note_html": _build_links_note(service_slug, service_label),
        "sections": sections,
    }


