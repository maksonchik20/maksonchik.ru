"""Дополнительные SEO-лендинги для ниш бизнеса (группа 3 + холодные рассылки)."""


def _page(
    slug: str,
    url,
    *,
    accent: str,
    bg_word: str,
    eyebrow: str,
    title: str,
    description: str,
    h1: str,
    hero_lead: str,
    hero_bullets: list[str],
    marquee: list[str],
    features: list[str],
    audience: list[str],
    faq: list[dict],
    cta_text: str,
    preset: str = "service",
) -> dict:
    return {
        "slug": slug,
        "url": url(slug),
        "preset": preset,
        "accent": accent,
        "bg_word": bg_word,
        "eyebrow": eyebrow,
        "title": title,
        "description": description,
        "h1": h1,
        "hero_lead": hero_lead,
        "hero_bullets": hero_bullets,
        "marquee": marquee,
        "features": features,
        "audience": audience,
        "faq": faq,
        "cta_text": cta_text,
    }


